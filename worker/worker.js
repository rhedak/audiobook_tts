/**
 * Speech relay for the Audiobook TTS Builder, packaged as a Cloudflare
 * Worker.
 *
 * Microsoft's speech endpoint rejects WebSocket handshakes from arbitrary
 * web origins, so the page cannot connect to it directly. This Worker
 * stands in the middle: the page connects here, and the Worker connects
 * upstream claiming to be the Edge read-aloud extension -- the same thing
 * relay/tts_relay.py does on a user's own machine.
 *
 * Deploy:
 *   npm install -g wrangler
 *   wrangler login
 *   wrangler deploy          # from this directory
 *
 * Then set the resulting wss://audiobook-tts-relay.<account>.workers.dev/tts-ws
 * as HOSTED_RELAY_URL in web/edge-tts.js.
 */

const UPSTREAM = "https://api.msedgeservices.com/tts/cognitiveservices/websocket/v1";

// The Edge extension origin Microsoft expects to see.
const SPOOFED_HEADERS = {
  "Origin": "chrome-extension://jdiccldimpdaibmpdkjnbmckianbfold",
  "User-Agent":
    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
    "(KHTML, like Gecko) Chrome/143.0.0.0 Safari/537.36 Edg/143.0.0.0",
  "Pragma": "no-cache",
  "Cache-Control": "no-cache",
};

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.pathname === "/health") {
      return new Response("ok", {
        headers: { "Access-Control-Allow-Origin": "*" },
      });
    }

    if (url.pathname !== "/tts-ws") {
      return new Response("not found", { status: 404 });
    }
    if ((request.headers.get("Upgrade") || "").toLowerCase() !== "websocket") {
      return new Response("websocket required", { status: 426 });
    }

    // Abuse guard: when ALLOWED_ORIGINS is set (comma-separated), only
    // handshakes from those pages are relayed. Browsers always send Origin
    // on WebSocket upgrades, so this costs nothing and stops other sites
    // from embedding your relay. It is not protection against someone
    // deliberately forging headers outside a browser -- see README.
    const allowed = (env.ALLOWED_ORIGINS || "")
      .split(",").map((s) => s.trim()).filter(Boolean);
    if (allowed.length && !allowed.includes(request.headers.get("Origin") || "")) {
      return new Response("origin not allowed", { status: 403 });
    }

    // Auth tokens stay in the query string, generated by the page; they
    // pass through untouched.
    const upstream = new URL(UPSTREAM);
    upstream.search = url.search;

    let resp;
    try {
      resp = await fetch(upstream, {
        headers: { "Upgrade": "websocket", ...SPOOFED_HEADERS },
      });
    } catch {
      return new Response("upstream unreachable", { status: 502 });
    }
    const ms = resp.webSocket;
    if (!ms) {
      return new Response(`upstream refused (${resp.status})`, { status: 502 });
    }
    ms.accept();

    const pair = new WebSocketPair();
    pair[1].accept();

    pair[1].addEventListener("message", (e) => {
      if (ms.readyState === 1) ms.send(e.data);
    });
    ms.addEventListener("message", (e) => {
      if (pair[1].readyState === 1) pair[1].send(e.data);
    });
    const closeBoth = () => {
      try { pair[1].close(); } catch {}
      try { ms.close(); } catch {}
    };
    pair[1].addEventListener("close", closeBoth);
    ms.addEventListener("close", closeBoth);

    return new Response(null, { status: 101, webSocket: pair[0] });
  },
};
